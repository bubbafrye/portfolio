/**
 * Reads design-tokens/figma-variables.json and writes design-tokens/tokens.css
 * Supports schema v1 (Portfolio Variables Export plugin) and legacy collections format.
 * Prefer collection named "2026" when present.
 * Run: node scripts/build-tokens-css.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const dataPath = join(root, "design-tokens", "figma-variables.json");
const outPath = join(root, "design-tokens", "tokens.css");

const EASE_OUT = "cubic-bezier(0, 0, 0.2, 1)";

/** CSS-only durations not yet in the Figma 2026 collection. */
const APP_MOTION_ALIASES = [
  ["--see-more-btn-duration", "200ms"],
  ["--button-simple-duration", "300ms"],
  ["--see-more-btn-ease", "var(--anim-ease-out)"],
  ["--button-simple-ease", "var(--anim-ease-out)"],
];

const data = JSON.parse(readFileSync(dataPath, "utf8"));
const { modes, variables } = normalizeExport(data);

function normalizeExport(raw) {
  if (raw.schemaVersion === 1) {
    if (!raw.collections?.length) {
      throw new Error("schema v1 export has no collections");
    }
    const collection =
      raw.collections.find((c) => c.name === "2026") ??
      raw.collections.find((c) => (c.modes?.length ?? 0) > 1) ??
      raw.collections[0];
    const modes = collection.modes.map((m) => m.name);
    const variables = collection.variables.map((v) => ({
      name: v.name,
      resolvedType: v.resolvedType,
      valuesByMode: v.valuesByMode,
      css: v.css,
    }));
    return { modes, variables };
  }

  // Legacy format (pre-plugin or hand-maintained)
  const collection = raw.collections?.[0];
  if (!collection?.variables?.length) {
    throw new Error("Unrecognized figma-variables.json format");
  }
  const modes = collection.modes.map((m) => m.name);
  const variables = collection.variables;
  return { modes, variables };
}

function cssVarName(row) {
  if (row.css?.customProperty) return row.css.customProperty;
  return (
    "--" +
    String(row.name)
      .replace(/[^a-zA-Z0-9-]+/g, "-")
      .replace(/^-+|-+$/g, "")
  );
}

function inferUnit(name) {
  const key = String(name).toLowerCase();
  if (key.includes("angle")) return "deg";
  if (key.includes("distance")) return "px";
  if (key.includes("anim") || key.includes("timing")) return "ms";
  return "px";
}

function isFontFamily(name) {
  return name === "font/primary" || name === "font/secondary";
}

function formatEasing(value) {
  if (value && typeof value === "object") {
    const bezier =
      value.easingFunctionCubicBezier ??
      value.cubicBezier ??
      (value.x1 != null
        ? { x1: value.x1, y1: value.y1, x2: value.x2, y2: value.y2 }
        : null);
    if (bezier && bezier.x1 != null) {
      return `cubic-bezier(${bezier.x1}, ${bezier.y1}, ${bezier.x2}, ${bezier.y2})`;
    }
    if (value.type === "EASE_OUT" || value.type === "EASE_IN_OUT" || value.type === "EASE_IN") {
      return EASE_OUT;
    }
  }
  if (typeof value === "string" && value.includes("cubic-bezier")) return value;
  return EASE_OUT;
}

function cssLine(row, mode) {
  const typ = row.resolvedType;
  const v = row.valuesByMode[mode];
  if (v === undefined || v === null) return "";

  let val;
  if (typ === "EASING" || v === "[object Object]" || (v && typeof v === "object" && typ !== "COLOR")) {
    val = formatEasing(v);
  } else if (typ === "STRING") {
    if (isFontFamily(row.name)) {
      val = `"${String(v).replace(/"/g, "")}", sans-serif`;
    } else {
      val = JSON.stringify(v);
    }
  } else if (typ === "BOOLEAN") {
    val = v ? "true" : "false";
  } else if (typ === "FLOAT") {
    const unit = row.css?.unit ?? inferUnit(row.name);
    val = unit ? `${v}${unit}` : String(v);
  } else {
    val = String(v);
  }

  return `  ${cssVarName(row)}: ${val};`;
}

function isReducedMotionVar(row) {
  if (row.resolvedType !== "FLOAT") return false;
  const key = String(row.name).toLowerCase();
  return key.startsWith("anim/") || key.includes("timing");
}

let out =
  "/* Generated by scripts/build-tokens-css.mjs from design-tokens/figma-variables.json */\n";

for (const mode of modes) {
  out += `[data-theme="${mode}"] {\n`;
  for (const row of variables) {
    const line = cssLine(row, mode);
    if (line) out += line + "\n";
  }
  for (const [prop, value] of APP_MOTION_ALIASES) {
    out += `  ${prop}: ${value};\n`;
  }
  out += "}\n\n";
}

out += "/* prefers-reduced-motion: zero motion durations / distances */\n";
out += "@media (prefers-reduced-motion: reduce) {\n";
out += "  [data-theme] {\n";
for (const row of variables) {
  if (!isReducedMotionVar(row)) continue;
  const unit = row.css?.unit ?? inferUnit(row.name);
  out += `    ${cssVarName(row)}: 0${unit || ""};\n`;
}
out += "    --see-more-btn-duration: 0ms;\n";
out += "    --button-simple-duration: 0ms;\n";
out += "  }\n";
out += "}\n";

writeFileSync(outPath, out, "utf8");
console.log("Wrote", outPath, `(${modes.length} modes, ${variables.length} variables)`);
